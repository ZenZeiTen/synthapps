// Builds app/preload/chrome.bundle.cjs: Lintas' preload plus the
// <browser-action-list> element from electron-chrome-extensions, inlined
// because sandboxed preloads can only require('electron').
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const vendor = fs.readFileSync(require.resolve('electron-chrome-extensions/browser-action'), 'utf8');
const own = fs.readFileSync(path.join(root, 'app/preload/chrome.cjs'), 'utf8');
const out = `// GENERATED by scripts/build-preload.mjs — edit app/preload/chrome.cjs instead.
'use strict';
(function () {
  const module = { exports: {} };
  (function (module, exports) {
${vendor}
  })(module, module.exports);
  module.exports.injectBrowserAction();
})();
${own}
`;
fs.writeFileSync(path.join(root, 'app/preload/chrome.bundle.cjs'), out);
console.log('Wrote app/preload/chrome.bundle.cjs');
