<?php
/**
 * Render the admin screens that do not need WP_List_Table, with data, and check for output.
 * Any PHP notice or warning in a view fails the test.
 *
 * @package VisitorSentinel
 */

// phpcs:disable

use VisitorSentinel\Admin\Admin;

function vsen_seed_for_views() {
	WP_Stub::$user = null;
	list( , $a ) = vsen_pv( 'https://example.com/?gclid=VIEWCLICK123&utm_source=google&utm_medium=cpc&utm_campaign=brand', VSEN_VID, '', array(), array( 'HTTP_CF_IPCOUNTRY' => 'ID' ) );
	vsen_collect( array( 'e' => 'eng', 'pv' => $a['pv'], 't' => $a['t'], 'tt' => 30000, 'at' => 20000, 'sc' => 55, 'it' => 7 ) );
	vsen_collect( array( 'e' => 'click', 'k' => 'ad', 'pv' => $a['pv'], 't' => $a['t'], 'l' => 'sidebar <b>', 'ms' => 10, 'it' => 0, 'tr' => 0 ) );
	vsen_collect( array( 'e' => 'click', 'k' => 'out', 'pv' => $a['pv'], 't' => $a['t'], 'h' => 'https://partner.example.org/"><script>x</script>' ) );
	vsen_visit( array( 'gclid' => 'NOJSCLICK123' ), array( 'HTTP_USER_AGENT' => 'curl/8', 'REMOTE_ADDR' => '198.51.100.3' ) );
	WP_Stub::$user = (object) array( 'ID' => 1, 'roles' => array( 'administrator' ) );
}

function vsen_render( callable $fn ) {
	ob_start();
	try {
		$fn();
	} finally {
		$html = ob_get_clean();
	}
	return $html;
}

function test_view_dashboard() {
	vsen_seed_for_views();
	foreach ( array( 'today', '7d', '30d' ) as $range ) {
		$_GET = array( 'page' => 'vsen-dashboard', 'range' => $range );
		$html = vsen_render( array( new Admin(), 'page_dashboard' ) );
		check( false !== strpos( $html, 'id="vsen-chart"' ) );
		check( false !== strpos( $html, 'Fraudulent clicks' ) );
	}
	check( false === strpos( $html, '<script>x' ), 'stored values are escaped' );
	preg_match( '/data-series="([^"]+)"/', $html, $m );
	$series = json_decode( html_entity_decode( $m[1], ENT_QUOTES ), true );
	check_same( 30, count( $series ) );
	$today = end( $series );
	check_same( 1, $today['pageviews'] );
	check_same( 1, $today['visitors'] );
	check_same( 3, $today['ads'], 'two landings and one on-site ad click' );
	check_same( 1, $today['fraud'] );
	$_GET = array();
}

function test_view_visitor_detail() {
	vsen_seed_for_views();
	$id   = (int) $GLOBALS['wpdb']->get_var( 'SELECT id FROM wp_vsen_visitors WHERE is_bot = 0' );
	$_GET = array( 'page' => 'vsen-visitors', 'visitor' => $id );
	$html = vsen_render( array( new Admin(), 'page_visitors' ) );
	foreach ( array( '203.0.113.10', 'Paid ad visit', 'On-site ad click', 'Outbound link', 'scrolled 55%', 'Click was generated by script', 'Blocked' ) as $needle ) {
		check( false !== strpos( $html, $needle ), 'visitor page shows ' . $needle );
	}
	check( false === strpos( $html, '<script>x' ) && false === strpos( $html, 'sidebar <b>' ), 'stored values are escaped' );
	$_GET = array();
}

function test_view_settings() {
	WP_Stub::$user = (object) array( 'ID' => 1, 'roles' => array( 'administrator' ) );
	$html = vsen_render( array( new Admin(), 'page_settings' ) );
	foreach ( array( 'name="vsen_settings[ip_mode]"', 'name="vsen_settings[exclude_roles][]"', 'value="administrator"  checked="checked"', 'name="vsen_settings[auto_block_threshold]"', 'option_page' ) as $needle ) {
		check( false !== strpos( $html, $needle ), 'settings form has ' . $needle );
	}
}

function test_admin_pages_refuse_other_users() {
	WP_Stub::$user = (object) array( 'ID' => 2, 'roles' => array( 'editor' ) );
	foreach ( array( 'page_dashboard', 'page_settings' ) as $page ) {
		try {
			vsen_render( array( new Admin(), $page ) );
			check( false, $page . ' rendered for an editor' );
		} catch ( RuntimeException $e ) {
			check( 0 === strpos( $e->getMessage(), 'wp_die' ) );
		}
	}
}

function test_rest_live() {
	vsen_seed_for_views();
	$data = ( new Admin() )->rest_live()->get_data();
	check_same( 1, $data['count'] );
	check_same( '203.0.113.10', $data['sessions'][0]['ip'] );
	check_same( true, $data['sessions'][0]['paid'] );
}
