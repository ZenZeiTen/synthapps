// Writes the "Reference" section of LANGUAGE.md from src/scene/nodes.js,
// so the documentation cannot drift from what the language accepts.
//   node tools/gen-reference.mjs          update LANGUAGE.md
//   node tools/gen-reference.mjs --check  exit 1 if it is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { OBJECT_KINDS, MATERIAL_KINDS, SETTINGS_KINDS } from '../src/scene/nodes.js';
import { FUNCTIONS, METAL_COLORS } from '../src/lang/builtins.js';
import { EASINGS } from '../src/scene/animation.js';
import { UNITS } from '../src/lang/units.js';

const FILE = fileURLToPath(new URL('../LANGUAGE.md', import.meta.url));
const START = '<!-- reference:start -->', END = '<!-- reference:end -->';

function fmt(v) {
  if (v === null || v === undefined) return '—';
  if (Array.isArray(v)) return `[${v.map((x) => +x.toFixed(4)).join(', ')}]`;
  if (typeof v === 'number') return String(+v.toFixed(4));
  if (typeof v === 'boolean') return String(v);
  return String(v);
}

function typeName(spec) {
  if (spec.type === 'enum') return spec.values.join(' \\| ');
  return { size3: 'number or vec3', size2: 'number or vec2', auto: 'number or auto' }[spec.type] ?? spec.type;
}

function section(title, kinds, note = '') {
  let out = `### ${title}\n\n${note}`;
  for (const [kind, def] of Object.entries(kinds)) {
    out += `#### \`${kind}\`\n\n${def.doc}${def.children ? ' Can contain other objects.' : ''}\n\n`;
    out += '| Property | Type | Default | Meaning |\n|---|---|---|---|\n';
    for (const [name, spec] of Object.entries(def.props)) {
      let d = fmt(spec.default);
      // Show the camera's lens and sensor in millimetres, as people write them.
      if (kind === 'camera' && (name === 'lens' || name === 'sensor')) d = `${spec.default * 1000}mm`;
      out += `| \`${name}\` | ${typeName(spec)} | ${d} | ${spec.doc} |\n`;
    }
    out += '\n';
  }
  return out;
}

export function reference() {
  let out = `${START}\n<!-- Generated by tools/gen-reference.mjs from src/scene/nodes.js. Do not edit by hand. -->\n\n## Reference\n\n`;
  out += section('Settings', SETTINGS_KINDS, 'At most one of each; if a scene has two, the last one wins. `sky`, `hdri` and `background` are alternatives.\n\n');
  out += section('Objects', OBJECT_KINDS, 'Every object except the lights also takes the transform properties `position`, `rotate`, `scale`, `aim` and `visible`, and a `material` (or the `color` shorthand).\n\n');
  out += section('Materials', MATERIAL_KINDS, 'All kinds except `light` take the same properties; they differ only in their defaults.\n\n');
  out += '### Functions\n\n' + Object.keys(FUNCTIONS).map((f) => `\`${f}\``).join(', ') + '\n\n';
  out += '### Easings\n\n' + Object.keys(EASINGS).map((f) => `\`${f}\``).join(', ') + '\n\n';
  out += '### Metal colours\n\n' + Object.keys(METAL_COLORS).map((f) => `\`${f}\``).join(', ') + '\n\n';
  out += '### Units\n\n' + Object.keys(UNITS).map((u) => `\`${u}\``).join(', ') + '\n';
  return out + END;
}

export function updated(text) {
  const a = text.indexOf(START), b = text.indexOf(END);
  if (a < 0 || b < 0) throw new Error('LANGUAGE.md has no reference markers');
  return text.slice(0, a) + reference() + text.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = readFileSync(FILE, 'utf8');
  const next = updated(text);
  if (process.argv.includes('--check')) {
    if (next !== text) { console.error('LANGUAGE.md reference is out of date: run node tools/gen-reference.mjs'); process.exit(1); }
    console.log('LANGUAGE.md reference is up to date');
  } else {
    writeFileSync(FILE, next);
    console.log('updated LANGUAGE.md');
  }
}
