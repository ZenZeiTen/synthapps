// Writes the compact property cheat sheet used by the reality-js Claude skill
// (plugins/reality-js/skills/reality-js/references/cheatsheet.md) from
// src/scene/nodes.js, so the skill cannot drift from the language.
//   node tools/gen-cheatsheet.mjs          update the file
//   node tools/gen-cheatsheet.mjs --check  exit 1 if it is out of date

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { OBJECT_KINDS, MATERIAL_KINDS, SETTINGS_KINDS } from '../src/scene/nodes.js';
import { FUNCTIONS, METAL_COLORS } from '../src/lang/builtins.js';
import { EASINGS } from '../src/scene/animation.js';
import { UNITS } from '../src/lang/units.js';

export const FILE = fileURLToPath(new URL('../plugins/reality-js/skills/reality-js/references/cheatsheet.md', import.meta.url));

const TRANSFORM = ['position', 'rotate', 'scale', 'aim', 'visible', 'material', 'color'];

function fmt(kind, name, v) {
  if (v === null || v === undefined) return '—';
  if (kind === 'camera' && (name === 'lens' || name === 'sensor')) return `${v * 1000}mm`;
  if (Array.isArray(v)) return `[${v.map((x) => +x.toFixed(3)).join(', ')}]`;
  if (typeof v === 'number') return String(+v.toFixed(4));
  return String(v);
}

function typeHint(spec) {
  if (spec.type === 'enum') return spec.values.join('|');
  return { size3: 'n|vec3', size2: 'n|vec2', auto: 'n|auto' }[spec.type] ?? spec.type;
}

// One line per property: `name` type = default. Meaning.
function props(kind, def, skip = []) {
  return Object.entries(def.props)
    .filter(([name]) => !skip.includes(name))
    .map(([name, spec]) => `- \`${name}\` ${typeHint(spec)} = ${fmt(kind, name, spec.default)}. ${spec.doc}`)
    .join('\n');
}

export function cheatsheet() {
  let out = '<!-- Generated by reality-js/tools/gen-cheatsheet.mjs from src/scene/nodes.js. Do not edit by hand. -->\n';
  out += '# reality.js property cheat sheet\n\n';
  out += 'Every property of every node kind, one line each: `name` type = default. Units are metres, degrees, seconds, kelvin, lumens and nits.\n\n';
  out += '## Settings (one of each; `sky`, `hdri`, `background` are alternatives)\n\n';
  for (const [kind, def] of Object.entries(SETTINGS_KINDS)) out += `### ${kind}\n${def.doc}\n\n${props(kind, def)}\n\n`;
  out += '## Objects\n\nAll objects except `bulb` and `softbox` also take `position`, `rotate` (degrees, X then Y then Z), `scale`, `aim`, `visible`, `material`, and the `color` shorthand.\n\n';
  for (const [kind, def] of Object.entries(OBJECT_KINDS)) {
    const own = props(kind, def, TRANSFORM);
    out += `### ${kind}\n${def.doc}${def.children ? ' Contains other objects.' : ''}\n\n${own || '- (transform only)'}\n\n`;
  }
  const base = MATERIAL_KINDS.material;
  out += '## Materials\n\n### material (the general one; every other kind except `light` is this with other defaults)\n\n';
  out += props('material', base) + '\n\n';
  for (const [kind, def] of Object.entries(MATERIAL_KINDS)) {
    if (kind === 'material') continue;
    if (kind === 'light') { out += `### light\n${def.doc}\n\n${props(kind, def)}\n\n`; continue; }
    const diffs = Object.entries(def.props)
      .filter(([name, spec]) => JSON.stringify(spec.default) !== JSON.stringify(base.props[name]?.default))
      .map(([name, spec]) => `\`${name}\` = ${fmt(kind, name, spec.default)}`);
    out += `### ${kind}\n${def.doc} Defaults that differ: ${diffs.join(', ') || 'none'}.\n\n`;
  }
  out += '## Names\n\n';
  out += `- Functions: ${Object.keys(FUNCTIONS).join(', ')}\n`;
  out += `- Easings (for \`keys\` and \`ease()\`): ${Object.keys(EASINGS).join(', ')}\n`;
  out += `- Metal colours: ${Object.keys(METAL_COLORS).join(', ')}\n`;
  out += `- Units: ${Object.keys(UNITS).join(', ')}\n`;
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = cheatsheet();
  const current = existsSync(FILE) ? readFileSync(FILE, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (current !== text) { console.error('cheatsheet.md is out of date: run node tools/gen-cheatsheet.mjs'); process.exit(1); }
  } else if (current !== text) {
    writeFileSync(FILE, text);
    console.log('updated', FILE);
  }
}
